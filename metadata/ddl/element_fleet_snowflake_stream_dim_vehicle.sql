INSERT INTO AUDIT.SIT_CHECK_RESULTS (CHECK_NAME, CHECK_VALUE, EXPECTED_VALUE, CHECK_STATUS)
WITH unresolved_client_fk AS (
  SELECT VEHICLE_ID
  FROM CONFORMED.DIM_VEHICLE
  WHERE IS_CURRENT = TRUE
    AND CLIENT_SK IS NULL
)
SELECT
  'DIM_VEHICLE_UNRESOLVED_CLIENT_FK_STREAM',
  COUNT(*),
  0,
  IFF(COUNT(*) = 0, 'passed', 'failed')
FROM unresolved_client_fk;

SELECT *
FROM AUDIT.SIT_CHECK_RESULTS
WHERE CHECK_NAME LIKE 'DIM_VEHICLE%STREAM'
ORDER BY CHECKED_AT, CHECK_NAME;

