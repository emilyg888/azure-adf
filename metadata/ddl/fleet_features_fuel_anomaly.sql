CREATE TABLE IF NOT EXISTS AUDIT.FEATURE_TEST_RESULTS (
  CHECK_NAME VARCHAR,
  CHECK_VALUE NUMBER,
  EXPECTED_VALUE NUMBER,
  CHECK_STATUS VARCHAR,
  CHECKED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Run these checks after executing the procedure.
INSERT INTO AUDIT.FEATURE_TEST_RESULTS (CHECK_NAME, CHECK_VALUE, EXPECTED_VALUE, CHECK_STATUS)
SELECT
  'FEATURE_FUEL_ANOMALY_SCORE_ROWS',
  COUNT(*),
  (SELECT COUNT(*) FROM CONFORMED.FACT_FUEL_TRANSACTION),
  IFF(COUNT(*) = (SELECT COUNT(*) FROM CONFORMED.FACT_FUEL_TRANSACTION), 'passed', 'failed')
FROM FEATURES.FEATURE_FUEL_ANOMALY_SCORE;

INSERT INTO AUDIT.FEATURE_TEST_RESULTS (CHECK_NAME, CHECK_VALUE, EXPECTED_VALUE, CHECK_STATUS)
SELECT
  'FEATURE_FUEL_ANOMALY_SCORE_RANGE_FAILURES',
  COUNT(*),
  0,
  IFF(COUNT(*) = 0, 'passed', 'failed')
FROM FEATURES.FEATURE_FUEL_ANOMALY_SCORE
WHERE FUEL_ANOMALY_SCORE < 0
   OR FUEL_ANOMALY_SCORE > 100
   OR FUEL_ANOMALY_SCORE IS NULL;

SELECT *
FROM AUDIT.FEATURE_TEST_RESULTS
WHERE CHECK_NAME LIKE 'FEATURE_FUEL_ANOMALY%'
ORDER BY CHECKED_AT, CHECK_NAME;
