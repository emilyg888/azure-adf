    :RUN_ID AS CREATED_RUN_ID,
    CURRENT_TIMESTAMP() AS CREATED_AT
  FROM IDENTITY.VEHICLE_MATCH_CANDIDATE
  WHERE REVIEW_REQUIRED_FLAG = TRUE;

  CREATE OR REPLACE TABLE GOLD.CUSTOMER_360_MART AS
  WITH vehicle_metrics AS (
    SELECT
      GOLDEN_CUSTOMER_ID,
      COUNT_IF(RELATIONSHIP_STATUS = 'active') AS ACTIVE_VEHICLE_COUNT
    FROM GOLDEN.REL_CUSTOMER_VEHICLE
    GROUP BY GOLDEN_CUSTOMER_ID
  ),
  contract_metrics AS (
    SELECT
      C.GOLDEN_CUSTOMER_ID,
      COUNT_IF(LOWER(COALESCE(L.LEASE_STATUS, 'active')) = 'active') AS ACTIVE_CONTRACT_COUNT,
      SUM(COALESCE(L.MONTHLY_RENTAL_AMOUNT, 0) + COALESCE(L.MANAGEMENT_FEE_AMOUNT, 0)) AS MONTHLY_TCO
    FROM STG_FLEET.LEASING_CONTRACTS L
    JOIN GOLDEN.XREF_CUSTOMER_SOURCE C
      ON C.SOURCE_CUSTOMER_ID = L.CLIENT_ID
    WHERE L._IS_LATEST_FOR_BUSINESS_KEY = TRUE
      AND L._LATEST_RESOLUTION_STATUS = 'resolved'
      AND L._IS_EXACT_DUPLICATE = FALSE
      AND COALESCE(L._DQ_STATUS, 'passed') = 'passed'
    GROUP BY C.GOLDEN_CUSTOMER_ID
  ),
  fuel_metrics AS (
    SELECT
      C.GOLDEN_CUSTOMER_ID,
      SUM(COALESCE(F.GROSS_AMOUNT, 0)) AS FUEL_COST_90D
    FROM STG_FLEET.FUEL_CARD_TRANSACTIONS F
    JOIN GOLDEN.XREF_CUSTOMER_SOURCE C
      ON C.SOURCE_CUSTOMER_ID = F.CLIENT_ID
    WHERE TO_DATE(F.TRANSACTION_DATETIME) >= DATEADD(day, -90, COALESCE(:BATCH_DATE, CURRENT_DATE()))
    GROUP BY C.GOLDEN_CUSTOMER_ID
  ),
  maintenance_metrics AS (
    SELECT
      C.GOLDEN_CUSTOMER_ID,
      SUM(COALESCE(M.INVOICE_AMOUNT, M.AUTHORISED_AMOUNT, 0)) AS MAINTENANCE_COST_90D
    FROM STG_FLEET.MAINTENANCE_WORK_ORDERS M
    JOIN GOLDEN.XREF_CUSTOMER_SOURCE C
      ON C.SOURCE_CUSTOMER_ID = M.CLIENT_ID
    WHERE TO_DATE(COALESCE(M.CLOSED_DATE, M.OPENED_DATE)) >= DATEADD(day, -90, COALESCE(:BATCH_DATE, CURRENT_DATE()))
      AND M._IS_LATEST_FOR_BUSINESS_KEY = TRUE
      AND M._LATEST_RESOLUTION_STATUS = 'resolved'
      AND M._IS_EXACT_DUPLICATE = FALSE
      AND COALESCE(M._DQ_STATUS, 'passed') = 'passed'
    GROUP BY C.GOLDEN_CUSTOMER_ID
  ),
  ev_metrics AS (
    SELECT
      C.GOLDEN_CUSTOMER_ID,
      SUM(COALESCE(E.GROSS_AMOUNT, 0)) AS EV_CHARGING_COST_90D
    FROM STG_FLEET.EV_CHARGING_SESSIONS E
    JOIN GOLDEN.XREF_CUSTOMER_SOURCE C
      ON C.SOURCE_CUSTOMER_ID = E.CLIENT_ID
    WHERE TO_DATE(E.SESSION_START_DATETIME) >= DATEADD(day, -90, COALESCE(:BATCH_DATE, CURRENT_DATE()))
      AND E._IS_LATEST_FOR_BUSINESS_KEY = TRUE
      AND E._LATEST_RESOLUTION_STATUS = 'resolved'
      AND E._IS_EXACT_DUPLICATE = FALSE
      AND COALESCE(E._DQ_STATUS, 'passed') = 'passed'
    GROUP BY C.GOLDEN_CUSTOMER_ID
  ),
  claim_metrics AS (
    SELECT
      C.GOLDEN_CUSTOMER_ID,
      COUNT_IF(LOWER(COALESCE(I.CLAIM_STATUS, 'open')) NOT IN ('closed', 'settled', 'declined')) AS OPEN_CLAIM_COUNT
    FROM STG_FLEET.INSURANCE_CLAIMS I
    JOIN GOLDEN.XREF_CUSTOMER_SOURCE C
      ON C.SOURCE_CUSTOMER_ID = I.CLIENT_ID
    WHERE I._IS_LATEST_FOR_BUSINESS_KEY = TRUE
      AND I._LATEST_RESOLUTION_STATUS = 'resolved'
      AND I._IS_EXACT_DUPLICATE = FALSE
      AND COALESCE(I._DQ_STATUS, 'passed') = 'passed'
    GROUP BY C.GOLDEN_CUSTOMER_ID
  ),
  portal_metrics AS (
    SELECT
      C.GOLDEN_CUSTOMER_ID,
      LEAST(100, COUNT(*) * 0.5 + COUNT_IF(P.SLA_BREACH_FLAG = 'true') * 5)::NUMBER(18, 6) AS PORTAL_ACTIVITY_SCORE
    FROM STG_FLEET.CRM_CLIENT_PORTAL_EVENTS P
    JOIN GOLDEN.XREF_CUSTOMER_SOURCE C
      ON C.SOURCE_CUSTOMER_ID = P.CLIENT_ID
    WHERE TO_DATE(P.EVENT_DATETIME) >= DATEADD(day, -90, COALESCE(:BATCH_DATE, CURRENT_DATE()))
      AND P._IS_LATEST_FOR_BUSINESS_KEY = TRUE
      AND P._LATEST_RESOLUTION_STATUS = 'resolved'
      AND P._IS_EXACT_DUPLICATE = FALSE
      AND COALESCE(P._DQ_STATUS, 'passed') = 'passed'
    GROUP BY C.GOLDEN_CUSTOMER_ID
  )
  SELECT
    C.GOLDEN_CUSTOMER_ID,
    C.CUSTOMER_NAME,
    C.CUSTOMER_SEGMENT,
    COALESCE(V.ACTIVE_VEHICLE_COUNT, 0) AS ACTIVE_VEHICLE_COUNT,
    COALESCE(K.ACTIVE_CONTRACT_COUNT, 0) AS ACTIVE_CONTRACT_COUNT,
    COALESCE(K.MONTHLY_TCO, 0) AS MONTHLY_TCO,
    COALESCE(M.MAINTENANCE_COST_90D, 0) AS MAINTENANCE_COST_90D,
    COALESCE(F.FUEL_COST_90D, 0) AS FUEL_COST_90D,
    COALESCE(E.EV_CHARGING_COST_90D, 0) AS EV_CHARGING_COST_90D,
    COALESCE(CL.OPEN_CLAIM_COUNT, 0) AS OPEN_CLAIM_COUNT,
    COALESCE(P.PORTAL_ACTIVITY_SCORE, 0) AS PORTAL_ACTIVITY_SCORE,
    LEAST(100, COALESCE(V.ACTIVE_VEHICLE_COUNT, 0) * 1.5 + COALESCE(CL.OPEN_CLAIM_COUNT, 0) * 8)::NUMBER(18, 6) AS SERVICE_RISK_SCORE,
    IFF(COALESCE(V.ACTIVE_VEHICLE_COUNT, 0) > 0, 50, 0)::NUMBER(18, 6) AS FLEET_GROWTH_OPPORTUNITY_SCORE,
    IFF(C.GOLDEN_CUSTOMER_ID IS NOT NULL, 'certified', 'failed') AS DATA_QUALITY_STATUS,
    C.IDENTITY_RESOLUTION_CONFIDENCE,
    :RUN_ID AS CREATED_RUN_ID,
    CURRENT_TIMESTAMP() AS BUILT_AT
  FROM GOLDEN.GOLDEN_CUSTOMER C
  LEFT JOIN vehicle_metrics V
    ON V.GOLDEN_CUSTOMER_ID = C.GOLDEN_CUSTOMER_ID
  LEFT JOIN contract_metrics K
    ON K.GOLDEN_CUSTOMER_ID = C.GOLDEN_CUSTOMER_ID
  LEFT JOIN fuel_metrics F
    ON F.GOLDEN_CUSTOMER_ID = C.GOLDEN_CUSTOMER_ID
  LEFT JOIN maintenance_metrics M
    ON M.GOLDEN_CUSTOMER_ID = C.GOLDEN_CUSTOMER_ID
  LEFT JOIN ev_metrics E
    ON E.GOLDEN_CUSTOMER_ID = C.GOLDEN_CUSTOMER_ID
  LEFT JOIN claim_metrics CL
    ON CL.GOLDEN_CUSTOMER_ID = C.GOLDEN_CUSTOMER_ID
  LEFT JOIN portal_metrics P
    ON P.GOLDEN_CUSTOMER_ID = C.GOLDEN_CUSTOMER_ID;

  INSERT INTO AUDIT.SIT_CHECK_RESULTS (CHECK_NAME, CHECK_VALUE, EXPECTED_VALUE, CHECK_STATUS)
  SELECT
    'CUSTOMER360_GOLDEN_CUSTOMER_WITHOUT_XREF',
    COUNT(*),
    0,
    IFF(COUNT(*) = 0, 'passed', 'failed')
  FROM GOLDEN.GOLDEN_CUSTOMER C
  LEFT JOIN GOLDEN.XREF_CUSTOMER_SOURCE X
    ON X.GOLDEN_CUSTOMER_ID = C.GOLDEN_CUSTOMER_ID
  WHERE X.GOLDEN_CUSTOMER_ID IS NULL;

  INSERT INTO AUDIT.SIT_CHECK_RESULTS (CHECK_NAME, CHECK_VALUE, EXPECTED_VALUE, CHECK_STATUS)
  SELECT
    'CUSTOMER360_CONFIDENCE_MISSING',
    COUNT(*),
    0,
    IFF(COUNT(*) = 0, 'passed', 'failed')
  FROM GOLD.CUSTOMER_360_MART
  WHERE IDENTITY_RESOLUTION_CONFIDENCE IS NULL;

  RETURN 'Built Customer 360 identity resolution for run_id=' || RUN_ID;
END;
$$;

