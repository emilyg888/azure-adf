    V.GOLDEN_VEHICLE_ID,
    C.GOLDEN_CUSTOMER_ID,
    F.CARD_STATUS,
    1.000000::NUMBER(10, 6) AS IDENTITY_RESOLUTION_CONFIDENCE,
    :RUN_ID AS CREATED_RUN_ID,
    CURRENT_TIMESTAMP() AS CREATED_AT,
    CURRENT_TIMESTAMP() AS UPDATED_AT
  FROM IDENTITY.STD_FUEL_CARD F
  LEFT JOIN GOLDEN.GOLDEN_VEHICLE V
    ON V.VEHICLE_ID = F.SOURCE_VEHICLE_ID
  LEFT JOIN GOLDEN.GOLDEN_CUSTOMER C
    ON C.PRIMARY_SOURCE_CUSTOMER_ID = F.SOURCE_CUSTOMER_ID;

  CREATE OR REPLACE TABLE GOLDEN.XREF_FUEL_CARD_SOURCE AS
  SELECT
    F.GOLDEN_FUEL_CARD_ID,
    F.GOLDEN_VEHICLE_ID,
    F.GOLDEN_CUSTOMER_ID,
    'STG_FLEET.FUEL_CARDS' AS SOURCE_SYSTEM,
    S.SOURCE_FUEL_CARD_ID,
    F.IDENTITY_RESOLUTION_CONFIDENCE AS MATCH_CONFIDENCE,
    'deterministic_fuel_card_id' AS MATCH_METHOD,
    'same_fuel_card_id' AS MATCH_REASON_CODE,
    :RUN_ID AS CREATED_RUN_ID,
    CURRENT_TIMESTAMP() AS CREATED_AT
  FROM GOLDEN.GOLDEN_FUEL_CARD F
  JOIN IDENTITY.STD_FUEL_CARD S
    ON F.GOLDEN_FUEL_CARD_ID = CONCAT('GFCARD_', SUBSTR(SHA2(S.SOURCE_FUEL_CARD_ID, 256), 1, 16));

  CREATE OR REPLACE TABLE GOLDEN.XREF_DEVICE_SOURCE AS
  SELECT
    CONCAT('GDEV_', SUBSTR(SHA2(STD_PROVIDER_DEVICE_ID, 256), 1, 16)) AS GOLDEN_DEVICE_ID,
    V.GOLDEN_VEHICLE_ID,
    V.GOLDEN_CUSTOMER_ID,
    D.SOURCE_SYSTEM_ID AS SOURCE_SYSTEM,
    D.SOURCE_DEVICE_ID,
    1.000000::NUMBER(10, 6) AS MATCH_CONFIDENCE,
    'deterministic_provider_device_id' AS MATCH_METHOD,
    'same_device_vehicle_assignment' AS MATCH_REASON_CODE,
    :RUN_ID AS CREATED_RUN_ID,
    CURRENT_TIMESTAMP() AS CREATED_AT
  FROM IDENTITY.STD_DEVICE D
  LEFT JOIN GOLDEN.GOLDEN_VEHICLE V
    ON V.VEHICLE_ID = D.SOURCE_VEHICLE_ID;

  CREATE OR REPLACE TABLE GOLDEN.REL_CUSTOMER_VEHICLE AS
  SELECT
    GOLDEN_CUSTOMER_ID,
    GOLDEN_VEHICLE_ID,
    IFF(LOWER(COALESCE(VEHICLE_STATUS, 'active')) = 'active', 'active', 'inactive') AS RELATIONSHIP_STATUS,
    NULL::DATE AS RELATIONSHIP_START_DATE,
    NULL::DATE AS RELATIONSHIP_END_DATE,
    :RUN_ID AS CREATED_RUN_ID,
    CURRENT_TIMESTAMP() AS CREATED_AT
  FROM GOLDEN.GOLDEN_VEHICLE
  WHERE GOLDEN_CUSTOMER_ID IS NOT NULL;

  CREATE OR REPLACE TABLE GOLDEN.REL_CUSTOMER_CONTRACT AS
