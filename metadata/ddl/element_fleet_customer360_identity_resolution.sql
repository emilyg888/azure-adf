    CURRENT_TIMESTAMP() AS CREATED_AT
  FROM STG_FLEET.LEASING_CONTRACTS L
  JOIN GOLDEN.GOLDEN_CUSTOMER C
    ON C.PRIMARY_SOURCE_CUSTOMER_ID = L.CLIENT_ID
  WHERE L._IS_LATEST_FOR_BUSINESS_KEY = TRUE
    AND L._LATEST_RESOLUTION_STATUS = 'resolved'
    AND L._IS_EXACT_DUPLICATE = FALSE
    AND COALESCE(L._DQ_STATUS, 'passed') = 'passed';

  CREATE OR REPLACE TABLE GOLDEN.REL_VEHICLE_FUEL_CARD AS
  SELECT
    GOLDEN_VEHICLE_ID,
    GOLDEN_FUEL_CARD_ID,
    LOWER(COALESCE(CARD_STATUS, 'active')) AS RELATIONSHIP_STATUS,
    :RUN_ID AS CREATED_RUN_ID,
    CURRENT_TIMESTAMP() AS CREATED_AT
  FROM GOLDEN.GOLDEN_FUEL_CARD
  WHERE GOLDEN_VEHICLE_ID IS NOT NULL;

  CREATE OR REPLACE TABLE GOLDEN.REL_VEHICLE_TELEMATICS_DEVICE AS
