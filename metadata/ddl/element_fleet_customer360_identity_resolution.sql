  FROM STG_FLEET.CRM_CLIENT_PORTAL_EVENTS P
  JOIN GOLDEN.GOLDEN_CUSTOMER C
    ON C.PRIMARY_SOURCE_CUSTOMER_ID = P.CLIENT_ID
  WHERE P.PORTAL_USER_ID IS NOT NULL
    AND P.PORTAL_USER_ID <> '';

  CREATE OR REPLACE TABLE GOVERNANCE.IDENTITY_REVIEW_QUEUE AS
  SELECT
    CONCAT('REV_', SUBSTR(SHA2(CONCAT_WS('|', ENTITY_TYPE, SOURCE_RECORD_A, SOURCE_RECORD_B, MATCH_METHOD), 256), 1, 16)) AS REVIEW_CASE_ID,
    ENTITY_TYPE,
    SOURCE_RECORD_A AS CANDIDATE_RECORD_A,
    SOURCE_RECORD_B AS CANDIDATE_RECORD_B,
    MATCH_SCORE,
    MATCH_REASON_CODE AS MATCH_REASON,
    'name_or_identifier_conflict' AS CONFLICTING_ATTRIBUTES,
    'steward_review' AS RECOMMENDED_ACTION,
    'open' AS REVIEW_STATUS,
    NULL::VARCHAR AS REVIEWED_BY,
    NULL::TIMESTAMP_NTZ AS REVIEWED_AT,
    :RUN_ID AS CREATED_RUN_ID,
    CURRENT_TIMESTAMP() AS CREATED_AT
  FROM IDENTITY.CUSTOMER_MATCH_CANDIDATE
  WHERE REVIEW_REQUIRED_FLAG = TRUE
  UNION ALL
  SELECT
    CONCAT('REV_', SUBSTR(SHA2(CONCAT_WS('|', ENTITY_TYPE, SOURCE_RECORD_A, SOURCE_RECORD_B, MATCH_METHOD), 256), 1, 16)) AS REVIEW_CASE_ID,
    ENTITY_TYPE,
    SOURCE_RECORD_A AS CANDIDATE_RECORD_A,
