    :RUN_ID AS CREATED_RUN_ID,
    CURRENT_TIMESTAMP() AS CREATED_AT
  FROM GOLDEN.GOLDEN_ACCOUNT A
  JOIN IDENTITY.STD_ACCOUNT S
