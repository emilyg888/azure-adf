CREATE OR REPLACE PROCEDURE IDENTITY.BUILD_CUSTOMER360_IDENTITY(BATCH_DATE DATE, RUN_ID VARCHAR)
RETURNS VARCHAR
LANGUAGE SQL
AS
$$
BEGIN
  CREATE OR REPLACE TABLE IDENTITY.STD_CUSTOMER AS
  SELECT
    'CONFORMED' AS SOURCE_SYSTEM_ID,
    CLIENT_ID AS SOURCE_CUSTOMER_ID,
    CLIENT_NAME AS CUSTOMER_NAME,
    UPPER(REGEXP_REPLACE(COALESCE(CLIENT_NAME, ''), '[^A-Z0-9 ]', '')) AS STD_CUSTOMER_NAME_RAW,
    TRIM(REGEXP_REPLACE(
      REGEXP_REPLACE(UPPER(COALESCE(CLIENT_NAME, '')), '\\bPTY LTD\\b|\\bPROPRIETARY LIMITED\\b|\\bLIMITED\\b|\\bLTD\\b|\\bINC\\b|\\bCORP\\b', ''),
      '\\s+',
      ' '
    )) AS STD_CUSTOMER_NAME,
    REGEXP_REPLACE(COALESCE(ABN, ''), '[^0-9]', '') AS STD_ABN,
    LOWER(TRIM(EMAIL_DOMAIN)) AS STD_EMAIL_DOMAIN,
    TRIM(REGEXP_REPLACE(UPPER(COALESCE(ADDRESS_LINE_1, '')), '\\s+', ' ')) AS STD_ADDRESS_LINE_1,
    TRIM(REGEXP_REPLACE(UPPER(COALESCE(SUBURB, '')), '\\s+', ' ')) AS STD_SUBURB,
    UPPER(TRIM(COALESCE(STATE, HEADQUARTERS_STATE))) AS STD_STATE,
    REGEXP_REPLACE(COALESCE(POSTCODE, ''), '[^0-9]', '') AS STD_POSTCODE,
    UPPER(TRIM(COALESCE(COUNTRY, 'AU'))) AS STD_COUNTRY,
    COALESCE(INDUSTRY_SEGMENT, FLEET_SIZE_BAND) AS CUSTOMER_SEGMENT,
    CLIENT_STATUS AS CUSTOMER_STATUS,
    SOURCE_UPDATED_AT,
    :RUN_ID AS CREATED_RUN_ID,
    CURRENT_TIMESTAMP() AS STANDARDISED_AT
  FROM CONFORMED.DIM_CLIENT
  WHERE IS_CURRENT = TRUE
    AND COALESCE(DELETED_FLAG, FALSE) = FALSE;

  CREATE OR REPLACE TABLE IDENTITY.STD_VEHICLE AS
  SELECT
    'CONFORMED' AS SOURCE_SYSTEM_ID,
    VEHICLE_ID AS SOURCE_VEHICLE_ID,
    CLIENT_ID AS SOURCE_CUSTOMER_ID,
    UPPER(REGEXP_REPLACE(COALESCE(VIN, ''), '[^A-Z0-9]', '')) AS STD_VIN,
    UPPER(REGEXP_REPLACE(COALESCE(REGISTRATION_PLATE, ''), '[^A-Z0-9]', '')) AS STD_REGISTRATION_PLATE,
    UPPER(TRIM(COALESCE(TELEMATICS_DEVICE_ID, ''))) AS STD_TELEMATICS_DEVICE_ID,
    TELEMATICS_DEVICE_MODEL,
    TELEMATICS_INSTALL_DATE,
    STATE_REGISTERED,
    ASSET_TYPE,
    MAKE,
    MODEL,
    MODEL_YEAR,
    FUEL_TYPE,
    VEHICLE_STATUS,
    SOURCE_UPDATED_AT,
    :RUN_ID AS CREATED_RUN_ID,
    CURRENT_TIMESTAMP() AS STANDARDISED_AT
  FROM CONFORMED.DIM_VEHICLE
  WHERE IS_CURRENT = TRUE
    AND COALESCE(DELETED_FLAG, FALSE) = FALSE;

  CREATE OR REPLACE TABLE IDENTITY.STD_ACCOUNT AS
  SELECT
    'STG_FLEET.FINANCE_BILLING_INVOICES' AS SOURCE_SYSTEM_ID,
    INVOICE_ID AS SOURCE_ACCOUNT_ID,
    CLIENT_ID AS SOURCE_CUSTOMER_ID,
    UPPER(TRIM(COALESCE(PURCHASE_ORDER_NUMBER, INVOICE_NUMBER, INVOICE_ID))) AS STD_ACCOUNT_KEY,
    'billing_invoice' AS ACCOUNT_TYPE,
    INVOICE_STATUS AS ACCOUNT_STATUS,
    UPDATED_AT AS SOURCE_UPDATED_AT,
    :RUN_ID AS CREATED_RUN_ID,
    CURRENT_TIMESTAMP() AS STANDARDISED_AT
  FROM STG_FLEET.FINANCE_BILLING_INVOICES
  WHERE _IS_LATEST_FOR_BUSINESS_KEY = TRUE
    AND _LATEST_RESOLUTION_STATUS = 'resolved'
    AND _IS_EXACT_DUPLICATE = FALSE
    AND COALESCE(_DQ_STATUS, 'passed') = 'passed';

  CREATE OR REPLACE TABLE IDENTITY.STD_FUEL_CARD AS
  SELECT
    'STG_FLEET.FUEL_CARDS' AS SOURCE_SYSTEM_ID,
    FUEL_CARD_ID AS SOURCE_FUEL_CARD_ID,
    VEHICLE_ID AS SOURCE_VEHICLE_ID,
    CLIENT_ID AS SOURCE_CUSTOMER_ID,
    SHA2(FUEL_CARD_ID, 256) AS HASHED_FUEL_CARD_NUMBER,
    CARD_STATUS,
    UPDATED_AT AS SOURCE_UPDATED_AT,
    :RUN_ID AS CREATED_RUN_ID,
    CURRENT_TIMESTAMP() AS STANDARDISED_AT
  FROM STG_FLEET.FUEL_CARDS
  WHERE _IS_LATEST_FOR_BUSINESS_KEY = TRUE
    AND _LATEST_RESOLUTION_STATUS = 'resolved'
    AND _IS_EXACT_DUPLICATE = FALSE
    AND COALESCE(_DQ_STATUS, 'passed') = 'passed';

  CREATE OR REPLACE TABLE IDENTITY.STD_DEVICE AS
  SELECT DISTINCT
    'CONFORMED.DIM_VEHICLE' AS SOURCE_SYSTEM_ID,
    STD_TELEMATICS_DEVICE_ID AS SOURCE_DEVICE_ID,
    SOURCE_VEHICLE_ID,
    NULL::VARCHAR AS PROVIDER_NAME,
    STD_TELEMATICS_DEVICE_ID AS STD_PROVIDER_DEVICE_ID,
    SOURCE_UPDATED_AT,
    :RUN_ID AS CREATED_RUN_ID,
    CURRENT_TIMESTAMP() AS STANDARDISED_AT
  FROM IDENTITY.STD_VEHICLE
  WHERE STD_TELEMATICS_DEVICE_ID IS NOT NULL
    AND STD_TELEMATICS_DEVICE_ID <> ''
  UNION
  SELECT DISTINCT
    'STG_FLEET.TELEMATICS_DAILY' AS SOURCE_SYSTEM_ID,
    UPPER(TRIM(TELEMATICS_DEVICE_ID)) AS SOURCE_DEVICE_ID,
    VEHICLE_ID AS SOURCE_VEHICLE_ID,
    PROVIDER_NAME,
    CONCAT(UPPER(TRIM(PROVIDER_NAME)), ':', UPPER(TRIM(TELEMATICS_DEVICE_ID))) AS STD_PROVIDER_DEVICE_ID,
    NULL::TIMESTAMP_NTZ AS SOURCE_UPDATED_AT,
    :RUN_ID AS CREATED_RUN_ID,
    CURRENT_TIMESTAMP() AS STANDARDISED_AT
  FROM STG_FLEET.TELEMATICS_DAILY
  WHERE TELEMATICS_DEVICE_ID IS NOT NULL
    AND TELEMATICS_DEVICE_ID <> '';

  CREATE OR REPLACE TABLE IDENTITY.CUSTOMER_MATCH_CANDIDATE AS
  WITH deterministic AS (
    SELECT
      SHA2(CONCAT_WS('|', 'customer', C1.SOURCE_RECORD_A, C1.SOURCE_RECORD_B, C1.MATCH_METHOD), 256) AS CANDIDATE_ID,
      'customer' AS ENTITY_TYPE,
      C1.SOURCE_RECORD_A,
      C1.SOURCE_RECORD_B,
      1.000000::NUMBER(10, 6) AS MATCH_SCORE,
      C1.MATCH_METHOD,
      C1.MATCH_REASON_CODE,
      TRUE AS AUTO_MATCH_FLAG,
      FALSE AS REVIEW_REQUIRED_FLAG,
      :RUN_ID AS CREATED_RUN_ID,
      CURRENT_TIMESTAMP() AS CREATED_AT
    FROM (
      SELECT
        A.SOURCE_CUSTOMER_ID AS SOURCE_RECORD_A,
        B.SOURCE_CUSTOMER_ID AS SOURCE_RECORD_B,
        'deterministic_source_customer_id' AS MATCH_METHOD,
        'same_source_customer_id' AS MATCH_REASON_CODE
      FROM IDENTITY.STD_CUSTOMER A
      JOIN IDENTITY.STD_CUSTOMER B
        ON A.SOURCE_CUSTOMER_ID = B.SOURCE_CUSTOMER_ID
       AND A.SOURCE_SYSTEM_ID <= B.SOURCE_SYSTEM_ID
      WHERE A.SOURCE_CUSTOMER_ID IS NOT NULL
      UNION ALL
      SELECT
        A.SOURCE_CUSTOMER_ID AS SOURCE_RECORD_A,
        B.SOURCE_CUSTOMER_ID AS SOURCE_RECORD_B,
        'deterministic_abn' AS MATCH_METHOD,
        'same_abn' AS MATCH_REASON_CODE
      FROM IDENTITY.STD_CUSTOMER A
      JOIN IDENTITY.STD_CUSTOMER B
        ON A.STD_ABN = B.STD_ABN
       AND A.SOURCE_CUSTOMER_ID < B.SOURCE_CUSTOMER_ID
      WHERE A.STD_ABN IS NOT NULL
        AND LENGTH(A.STD_ABN) > 0
    ) C1
  ),
  fuzzy_scored AS (
    SELECT
      SHA2(CONCAT_WS('|', 'customer', A.SOURCE_CUSTOMER_ID, B.SOURCE_CUSTOMER_ID, 'fuzzy_name_state'), 256) AS CANDIDATE_ID,
      'customer' AS ENTITY_TYPE,
      A.SOURCE_CUSTOMER_ID AS SOURCE_RECORD_A,
      B.SOURCE_CUSTOMER_ID AS SOURCE_RECORD_B,
      (
        0.80 * (
          1 - (
            EDITDISTANCE(A.STD_CUSTOMER_NAME, B.STD_CUSTOMER_NAME)
            / NULLIF(GREATEST(LENGTH(A.STD_CUSTOMER_NAME), LENGTH(B.STD_CUSTOMER_NAME)), 0)
          )
        )
        + 0.20 * IFF(COALESCE(A.STD_POSTCODE, '') = COALESCE(B.STD_POSTCODE, ''), 1, 0)
      )::NUMBER(10, 6) AS MATCH_SCORE,
      'fuzzy_name_state' AS MATCH_METHOD,
      'name_address_domain_block' AS MATCH_REASON_CODE
    FROM IDENTITY.STD_CUSTOMER A
    JOIN IDENTITY.STD_CUSTOMER B
      ON SUBSTR(A.STD_CUSTOMER_NAME, 1, 5) = SUBSTR(B.STD_CUSTOMER_NAME, 1, 5)
     AND (
       COALESCE(A.STD_POSTCODE, '') = COALESCE(B.STD_POSTCODE, '')
       OR COALESCE(A.STD_EMAIL_DOMAIN, '') = COALESCE(B.STD_EMAIL_DOMAIN, '')
     )
     AND A.SOURCE_CUSTOMER_ID < B.SOURCE_CUSTOMER_ID
    WHERE LENGTH(A.STD_CUSTOMER_NAME) > 0
      AND LENGTH(B.STD_CUSTOMER_NAME) > 0
  ),
  fuzzy AS (
    SELECT
      CANDIDATE_ID,
      ENTITY_TYPE,
      SOURCE_RECORD_A,
      SOURCE_RECORD_B,
      MATCH_SCORE,
      MATCH_METHOD,
      MATCH_REASON_CODE,
      MATCH_SCORE >= 0.95 AS AUTO_MATCH_FLAG,
      MATCH_SCORE >= 0.70 AND MATCH_SCORE < 0.95 AS REVIEW_REQUIRED_FLAG,
      :RUN_ID AS CREATED_RUN_ID,
      CURRENT_TIMESTAMP() AS CREATED_AT
    FROM fuzzy_scored
  )
  SELECT * FROM deterministic
  UNION ALL
  SELECT * FROM fuzzy
  WHERE MATCH_SCORE >= 0.70;

  CREATE OR REPLACE TABLE IDENTITY.VEHICLE_MATCH_CANDIDATE AS
  SELECT
    SHA2(CONCAT_WS('|', 'vehicle', SOURCE_VEHICLE_ID, 'deterministic_vehicle_id'), 256) AS CANDIDATE_ID,
    'vehicle' AS ENTITY_TYPE,
